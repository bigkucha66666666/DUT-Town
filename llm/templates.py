def pool_for(table: dict, role: str, other_role: str) -> list[str]:
    """取角色组合的台词池；没登记的组合用通用池，**不跨角色串味**。"""
    return table.get((role, other_role)) or (GENERIC_OPENERS if table is OPENERS else GENERIC_FOLLOWUPS)

